import { cp, mkdir, readFile, writeFile, rm, access, readdir } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

// Build in an owned staging folder so the local AI server route stays intact.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const stage = join(root, '.pages-build');
const output = join(root, 'out');
const basePath = process.env.NEXT_PUBLIC_BASE_PATH || '';
if (basePath && !/^\/[a-zA-Z0-9_-]+(?:\/[a-zA-Z0-9_-]+)*$/.test(basePath)) {
  throw new Error('NEXT_PUBLIC_BASE_PATH must be empty or a path such as /engiquest, without a trailing slash.');
}
const marker = '.engiquest-generated';
async function exists(path) { try { await access(path); return true; } catch { return false; } }
async function resetOwnedDirectory(target) {
  const resolved = resolve(target);
  const inside = relative(root, resolved);
  if (!inside || inside.startsWith(`..${sep}`) || inside === '..' || ![stage, output].includes(resolved)) {
    throw new Error(`Refusing to replace a directory outside the build targets: ${resolved}`);
  }
  if (await exists(resolved)) {
    if (!await exists(join(resolved, marker))) {
      throw new Error(`Preserving existing folder ${resolved}: it was not created by this build script. Rename it in File Explorer, then try again.`);
    }
    await rm(resolved, { recursive: true, force: true });
  }
  await mkdir(resolved, { recursive: true });
  await writeFile(join(resolved, marker), 'Generated by EngiQuest build:pages. Safe to replace.\n');
}

await resetOwnedDirectory(stage);
for (const name of ['app', 'components', 'lib', 'public', 'package.json', 'tsconfig.json', 'next.config.ts', 'postcss.config.mjs']) {
  await cp(join(root, name), join(stage, name), {
    recursive: true,
    filter: source => source !== join(root, 'app', 'api'),
  });
}
// Explicitly omit server-only source and never copy .env files into the build.
await rm(join(stage, 'lib', 'engibot-server.ts'), { force: true });
console.log(`Building GitHub Pages edition (base path: ${basePath || '/'}). EngiBot uses written guides.`);
const result = spawnSync(process.execPath, [join(root, 'node_modules', 'next', 'dist', 'bin', 'next'), 'build', '--webpack'], {
  cwd: stage,
  stdio: 'inherit',
  env: {
    ...process.env,
    ENGIQUEST_STATIC_EXPORT: '1',
    NEXT_PUBLIC_STATIC_EXPORT: 'true',
    NEXT_PUBLIC_BASE_PATH: basePath,
    NEXT_TELEMETRY_DISABLED: '1',
  },
});
if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status || 1);
const built = join(stage, 'out');
await access(join(built, 'index.html'));
if (await exists(join(built, 'api'))) throw new Error('Static output unexpectedly contains an API directory.');
const html = await readFile(join(built, 'index.html'), 'utf8');
if (!html.includes(`${basePath}/_next/`)) throw new Error('The export is missing its expected asset prefix.');
async function audit(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    if (entry.name.startsWith('.env')) throw new Error('Unexpected environment file in static output.');
    if (entry.isDirectory()) await audit(join(directory, entry.name));
  }
}
await audit(built);
await resetOwnedDirectory(output);
await cp(built, output, { recursive: true });
await writeFile(join(output, '.nojekyll'), '');
await writeFile(join(stage, 'preview.json'), JSON.stringify({ basePath }));
console.log(`GitHub Pages files are ready in ${output}`);
console.log('Preview with: npm run preview:pages');
